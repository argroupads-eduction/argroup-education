export function normalizeCuratedPath(path: string): string {
  if (!path || path === '/') return '/';
  const trimmed = path.replace(/\/+$/, '') || '/';
  return trimmed.startsWith('/') ? trimmed : `/${trimmed}`;
}

export function getCuratedPageSeo(path: string): CuratedPageSeo | null {
  return CURATED_PAGE_SEO[normalizeCuratedPath(path)] ?? null;
}
